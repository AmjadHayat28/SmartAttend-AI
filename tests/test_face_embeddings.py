"""Embedding generation, eligibility, freshness and invalidation (fake engine; synthetic photos)."""

import json

import numpy as np
from sqlalchemy import func, select

from backend.app.face_recognition import model as face_model
from backend.app.models import AccountStatus, FaceEmbedding, Student, StudentFaceImage, User
from backend.app.scripts.generate_face_embeddings import backfill
from backend.app.services.face_embedding_service import generate_for_student, load_candidates
from tests import imaging
from tests.conftest import STUDENT_EMAIL
from tests.fake_face_engine import FakeEngine

API = "/api/v1"


def enroll_and_submit(client, headers):
    for pose, turn, seed in (("front", 0, 7), ("left", -30, 2), ("right", 30, 3)):  # YuNet-detectable synthetic faces
        res = client.post(f"{API}/me/face-photos", headers=headers, data={"pose": pose},
                          files={"file": ("p.png", imaging.png(imaging.face(turn=turn, seed=seed)), "image/png")})
        assert res.status_code == 201, res.text
    assert client.post(f"{API}/me/face-enrollment/submit", headers=headers).status_code == 200


def embeddings(db_session, student_id):
    with db_session() as db:
        return db.scalars(select(FaceEmbedding).where(FaceEmbedding.student_id == student_id)).all()


def test_approval_generates_one_embedding_per_photo(client, login, hod_h, ids, db_session, fake_face_engine):
    student_h = login(STUDENT_EMAIL)
    enroll_and_submit(client, student_h)
    assert embeddings(db_session, ids["student"]) == []  # nothing before approval
    assert client.post(f"{API}/face-enrollments/{ids['student']}/approve", headers=hod_h).status_code == 200
    rows = embeddings(db_session, ids["student"])  # generated by the background task
    assert len(rows) == 3
    with db_session() as db:
        photos = {p.id: p for p in db.scalars(select(StudentFaceImage).where(StudentFaceImage.student_id == ids["student"]))}
    for row in rows:
        vec = np.frombuffer(row.embedding_vector, dtype=np.float32)
        assert vec.shape == (row.dimension,) and abs(np.linalg.norm(vec) - 1) < 1e-4
        assert (row.model_name, row.model_version) == ("fake/test-engine", "v1")
        assert row.face_image_id in photos and row.det_score == 0.95
    # The API never exposes them.
    detail = client.get(f"{API}/face-enrollments/{ids['student']}", headers=hod_h).json()
    assert "embedding" not in json.dumps(detail).lower()


def test_retake_deletes_embeddings_and_reapproval_regenerates(client, login, hod_h, ids, db_session, audit):
    student_h = login(STUDENT_EMAIL)
    enroll_and_submit(client, student_h)
    client.post(f"{API}/face-enrollments/{ids['student']}/approve", headers=hod_h)
    old = {e.face_image_id: e.embedding_vector for e in embeddings(db_session, ids["student"])}
    res = client.post(f"{API}/face-enrollments/{ids['student']}/reject", headers=hod_h, json={"reason": "Glare"})
    assert res.status_code == 200 and embeddings(db_session, ids["student"]) == []  # unusable immediately
    assert audit("face_enrollment.rejected")[0].new_value["embeddings_removed"] == 3

    front = next(p for p in client.get(f"{API}/me/face-enrollment", headers=student_h).json()["photos"] if p["pose"] == "front")
    client.put(f"{API}/me/face-photos/{front['id']}", headers=student_h,
               files={"file": ("n.png", imaging.png(imaging.face(seed=77)), "image/png")})
    client.post(f"{API}/me/face-enrollment/submit", headers=student_h)
    client.post(f"{API}/face-enrollments/{ids['student']}/approve", headers=hod_h)
    new = {e.face_image_id: e.embedding_vector for e in embeddings(db_session, ids["student"])}
    assert len(new) == 3 and new[front["id"]] != old[front["id"]]  # replaced photo → new embedding


def test_only_eligible_students_get_embeddings(db_session, ids, fake_face_engine):
    with db_session() as db:
        pending = db.get(Student, ids["pending"])  # account pending, enrollment not approved
        report = generate_for_student(db, pending, fake_face_engine)
        assert report.eligible is False and report.created == 0
        candidates, missing = load_candidates(db, [ids["pending"], ids["student"]], fake_face_engine)
        assert candidates == [] and missing == set()


def test_suspended_account_is_never_a_candidate(client, login, hod_h, ids, db_session, fake_face_engine):
    enroll_and_submit(client, login(STUDENT_EMAIL))
    client.post(f"{API}/face-enrollments/{ids['student']}/approve", headers=hod_h)
    with db_session() as db:
        assert len(load_candidates(db, [ids["student"]], fake_face_engine)[0]) == 1
        db.get(User, ids["student_user"]).status = AccountStatus.SUSPENDED
        db.commit()
        assert load_candidates(db, [ids["student"]], fake_face_engine)[0] == []


def test_model_change_makes_embeddings_stale_and_backfill_regenerates(client, login, hod_h, ids, db_session):
    enroll_and_submit(client, login(STUDENT_EMAIL))
    client.post(f"{API}/face-enrollments/{ids['student']}/approve", headers=hod_h)
    v2 = FakeEngine(version="v2")
    face_model.set_engine(v2)
    with db_session() as db:
        candidates, missing = load_candidates(db, [ids["student"]], v2)
        assert candidates == [] and missing == {ids["student"]}  # stale rows are never used
        summary = backfill(db, v2)
        assert (summary.eligible, summary.processed, summary.successful, summary.failed) == (1, 1, 1, 0)
        assert {e.model_version for e in db.scalars(select(FaceEmbedding))} == {"v2"}
        assert len(load_candidates(db, [ids["student"]], v2)[0]) == 1
        again = backfill(db, v2)
        assert (again.processed, again.skipped) == (0, 1)  # up to date → skipped
        assert db.scalar(select(func.count(FaceEmbedding.id))) == 3  # no duplicates


def test_backfill_survives_a_bad_photo_and_purges_unapproved(client, login, hod_h, ids, db_session, isolated_uploads):
    enroll_and_submit(client, login(STUDENT_EMAIL))
    client.post(f"{API}/face-enrollments/{ids['student']}/approve", headers=hod_h)
    with db_session() as db:
        db.execute(FaceEmbedding.__table__.delete())
        photo = db.scalars(select(StudentFaceImage)).first()
        (isolated_uploads / photo.image_path).write_bytes(b"corrupt")
        db.commit()
        summary = backfill(db, FakeEngine())
        assert summary.failed == 1 and summary.processed == 1 and "could not be processed" in summary.failures[0]
        assert db.scalar(select(func.count(FaceEmbedding.id))) == 2  # the two good photos still embedded
        # A student whose enrollment is no longer approved has stray embeddings purged.
        db.get(Student, ids["student"]).face_enrollment_status = "rejected"
        db.commit()
        assert backfill(db, FakeEngine()).purged_students == 1
        assert db.scalar(select(func.count(FaceEmbedding.id))) == 0


def test_recognition_generates_missing_embeddings_lazily(client, login, hod_h, ids, db_session):
    enroll_and_submit(client, login(STUDENT_EMAIL))
    client.post(f"{API}/face-enrollments/{ids['student']}/approve", headers=hod_h)
    with db_session() as db:
        db.execute(FaceEmbedding.__table__.delete())  # e.g. the background task could not run
        db.commit()
        from backend.app.services.face_embedding_service import ensure_embeddings

        ensure_embeddings(db, [ids["student"]], face_model.get_engine())
        db.commit()
        assert db.scalar(select(func.count(FaceEmbedding.id))) == 3
