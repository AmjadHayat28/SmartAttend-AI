"""Alembic: the migration chain builds the same schema as the models, and round-trips.

Runs against a temporary SQLite file. PostgreSQL compatibility of the generated SQL is
checked offline (no server needed) by rendering the migrations with the PostgreSQL dialect.
"""

import io

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect, text

from backend.app.database.init_db import alembic_config


@pytest.fixture()
def cfg(tmp_path):
    url = f"sqlite:///{(tmp_path / 'migrations.db').as_posix()}"
    config = alembic_config(url)
    config.attributes["configure_logger"] = False
    return config, url


def test_upgrade_head_matches_models(cfg):
    config, url = cfg
    command.upgrade(config, "head")
    try:
        command.check(config)  # raises if models and migrations disagree
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"Models and migrations are out of sync: {exc}")
    tables = set(inspect(create_engine(url)).get_table_names())
    assert {"users", "hods", "teachers", "students", "batches", "semesters", "sections", "courses",
            "teacher_course_assignments", "student_course_enrollments", "audit_logs"} <= tables


def test_downgrade_and_reupgrade(cfg):
    config, _ = cfg
    command.upgrade(config, "head")
    command.downgrade(config, "base")
    command.upgrade(config, "head")


def test_0002_backfills_semester_names(cfg):
    config, url = cfg
    command.upgrade(config, "0001")
    engine = create_engine(url)
    with engine.begin() as conn:
        conn.execute(text("INSERT INTO departments (id, name, code, is_active) VALUES (1, 'CSE', 'CSE', 1)"))
        conn.execute(text("INSERT INTO batches (id, department_id, name, start_year, is_active) "
                          "VALUES (1, 1, 'F23', 2023, 1)"))
        conn.execute(text("INSERT INTO semesters (id, batch_id, department_id, number, is_current) "
                          "VALUES (1, 1, 1, 6, 1)"))
    engine.dispose()
    command.upgrade(config, "head")
    engine = create_engine(url)
    with engine.connect() as conn:
        assert conn.execute(text("SELECT name, is_active FROM semesters")).one() == ("Semester 6", 1)
    engine.dispose()


def test_0003_defaults_existing_students_to_not_started(cfg):
    config, url = cfg
    command.upgrade(config, "0002")
    engine = create_engine(url)
    with engine.begin() as conn:
        conn.execute(text("INSERT INTO departments (id, name, code, is_active) VALUES (1, 'CSE', 'CSE', 1)"))
        conn.execute(text("INSERT INTO batches (id, department_id, name, start_year, is_active) VALUES (1, 1, 'F23', 2023, 1)"))
        conn.execute(text("INSERT INTO semesters (id, batch_id, department_id, number, name, is_current, is_active) "
                          "VALUES (1, 1, 1, 6, 'Semester 6', 1, 1)"))
        conn.execute(text("INSERT INTO sections (id, semester_id, department_id, name, is_active) VALUES (1, 1, 1, 'A', 1)"))
        conn.execute(text("INSERT INTO users (id, email, password_hash, full_name, role, status, token_version) "
                          "VALUES (1, 's@x.edu', 'x', 'S', 'student', 'active', 0)"))
        conn.execute(text("INSERT INTO students (id, user_id, department_id, batch_id, semester_id, section_id, "
                          "registration_no) VALUES (1, 1, 1, 1, 1, 1, 'F23X01')"))
    engine.dispose()
    command.upgrade(config, "head")
    engine = create_engine(url)
    with engine.connect() as conn:
        assert conn.execute(text("SELECT face_enrollment_status FROM students")).scalar() == "not_started"
    engine.dispose()
    # And back down again cleanly (the enum CHECKs are dropped before their columns).
    command.downgrade(config, "0002")


def test_migrations_render_for_postgresql():
    """Offline (--sql) render with the PostgreSQL dialect: catches SQLite-only constructs."""
    config = alembic_config("postgresql+psycopg2://user:pass@localhost/smartclass_db")
    config.attributes["configure_logger"] = False
    buffer = io.StringIO()
    config.output_buffer = buffer
    command.upgrade(config, "head", sql=True)
    sql = buffer.getvalue()
    assert "CREATE UNIQUE INDEX uq_hods_current_department ON hods (department_id) WHERE is_current" in sql
    assert "BOOLEAN DEFAULT true NOT NULL" in sql
    assert "JSONB" in sql
    assert "DEFAULT 1" not in sql  # SQLite-style boolean defaults would fail on PostgreSQL
    # Each named CHECK constraint is emitted once per table.
    assert sql.count("CONSTRAINT ck_users_user_role") == 1
    # 0003: face enrollment
    assert "ADD COLUMN face_enrollment_status VARCHAR(32) DEFAULT 'not_started' NOT NULL" in sql
    assert sql.count("ADD CONSTRAINT ck_students_face_enrollment_status CHECK") == 1
    assert "ADD COLUMN quality JSONB" in sql
    # 0004: attendance workflow
    assert "UPDATE attendance_sessions SET status = 'finalized' WHERE status = 'submitted'" in sql
    assert "CHECK (status IN ('draft', 'finalized', 'cancelled'))" in sql
    assert ("CREATE UNIQUE INDEX uq_attendance_sessions_active_slot ON attendance_sessions "
            "(course_id, section_id, session_date, session_number) WHERE status <> 'cancelled'") in sql
    assert "ALTER TABLE attendance_sessions RENAME submitted_at TO finalized_at" in sql
    assert "ALTER TABLE attendance_records ALTER COLUMN status DROP NOT NULL" in sql
    # 0005: face recognition
    assert "CREATE TABLE attendance_recognition_runs" in sql and "CREATE TABLE attendance_recognition_faces" in sql
    assert ("CHECK (method IN ('face_recognition', 'face_recognition_confirmed', 'manual', 'hod_override'))") in sql
    assert "ALTER TABLE face_embeddings ADD COLUMN model_version VARCHAR(100) DEFAULT '' NOT NULL" in sql
    assert sql.count("CONSTRAINT ck_attendance_recognition_faces_face_decision") == 1
    # 0006: recognition diagnostics
    assert "ALTER TABLE attendance_recognition_runs ADD COLUMN diagnostics JSONB" in sql


def _seed_session(conn, status: str) -> None:
    for sql in (
        "INSERT INTO departments (id, name, code, is_active) VALUES (1, 'CSE', 'CSE', 1)",
        "INSERT INTO batches (id, department_id, name, start_year, is_active) VALUES (1, 1, 'F23', 2023, 1)",
        "INSERT INTO semesters (id, batch_id, department_id, number, name, is_current, is_active) "
        "VALUES (1, 1, 1, 6, 'Semester 6', 1, 1)",
        "INSERT INTO sections (id, semester_id, department_id, name, is_active) VALUES (1, 1, 1, 'A', 1)",
        "INSERT INTO courses (id, department_id, code, title, credit_hours, is_lab, is_active) "
        "VALUES (1, 1, 'CS-1', 'X', 3, 0, 1)",
        "INSERT INTO users (id, email, password_hash, full_name, role, status, token_version) "
        "VALUES (1, 't@x.edu', 'x', 'T', 'teacher', 'active', 0)",
        "INSERT INTO teachers (id, user_id, department_id, employee_id) VALUES (1, 1, 1, 'E1')",
        "INSERT INTO attendance_sessions (id, teacher_id, course_id, section_id, semester_id, department_id, "
        f"session_date, session_number, status, created_by_id) VALUES (1, 1, 1, 1, 1, 1, '2026-10-01', 1, '{status}', 1)",
    ):
        conn.execute(text(sql))


def test_0004_migrates_submitted_sessions_and_round_trips(cfg):
    config, url = cfg
    command.upgrade(config, "0003")
    engine = create_engine(url)
    with engine.begin() as conn:
        _seed_session(conn, "submitted")
    engine.dispose()
    command.upgrade(config, "head")
    engine = create_engine(url)
    with engine.connect() as conn:
        assert conn.execute(text("SELECT status, version FROM attendance_sessions")).one() == ("finalized", 1)
    engine.dispose()
    command.downgrade(config, "0003")
    engine = create_engine(url)
    with engine.connect() as conn:
        assert conn.execute(text("SELECT status FROM attendance_sessions")).scalar() == "submitted"
    engine.dispose()


def test_0004_downgrade_refuses_to_lose_cancelled_sessions(cfg):
    config, url = cfg
    command.upgrade(config, "head")
    engine = create_engine(url)
    with engine.begin() as conn:
        _seed_session(conn, "cancelled")
    engine.dispose()
    with pytest.raises(RuntimeError, match="cancelled sessions"):
        command.downgrade(config, "0003")


def test_0005_round_trip_keeps_confirmed_marks_as_face_recognition(cfg):
    config, url = cfg
    command.upgrade(config, "head")
    engine = create_engine(url)
    with engine.begin() as conn:
        _seed_session(conn, "draft")
        conn.execute(text("INSERT INTO students (id, user_id, department_id, batch_id, semester_id, section_id, "
                          "registration_no) VALUES (1, 1, 1, 1, 1, 1, 'F23X01')"))
        conn.execute(text("INSERT INTO attendance_records (id, session_id, student_id, teacher_id, course_id, "
                          "department_id, semester_id, section_id, attendance_date, session_number, status, method, "
                          "created_by_id) VALUES (1, 1, 1, 1, 1, 1, 1, 1, '2026-10-01', 1, 'present', "
                          "'face_recognition_confirmed', 1)"))
    engine.dispose()
    command.downgrade(config, "0004")
    engine = create_engine(url)
    with engine.connect() as conn:
        assert conn.execute(text("SELECT method FROM attendance_records")).scalar() == "face_recognition"
    engine.dispose()
    command.upgrade(config, "head")
